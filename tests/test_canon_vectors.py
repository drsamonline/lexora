"""Golden-vector conformance suite for lexcAN-0.1 (P1-T2 gate).

Every directory under tests/vectors/canonicalization/ holds input.bin,
expected_output.bin and meta.json. This suite locks the shipped rule set
byte-exactly: changing behavior without regenerating + reviewing vectors
fails here. Vectors are generated by scripts/gen_canon_vectors.py.

Honesty note: presence of these files satisfies the *mechanical* part of the
golden-vector gate. docs/CANONICALIZATION.md still requires owner sign-off to
move rule rows to "Frozen"; these tests do not grant that by themselves.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from lexora import CANONICALIZER_VERSION
from lexora.canonicalize import APPLIED_RULES_V0, canonicalize

VECTOR_ROOT = Path(__file__).parent / "vectors" / "canonicalization"

VECTORS = sorted(p.name for p in VECTOR_ROOT.iterdir() if p.is_dir()) if VECTOR_ROOT.exists() else []


def test_vectors_exist():
    assert VECTOR_ROOT.is_dir(), (
        "tests/vectors/canonicalization/ missing — run scripts/gen_canon_vectors.py"
    )
    assert len(VECTORS) >= 9, f"expected >=9 golden vectors, found {len(VECTORS)}"


@pytest.mark.parametrize("vid", VECTORS)
def test_golden_vector_byte_exact(vid: str):
    d = VECTOR_ROOT / vid
    raw = (d / "input.bin").read_bytes()
    expected = (d / "expected_output.bin").read_bytes()
    meta = json.loads((d / "meta.json").read_text())

    got = canonicalize(raw, declared_encoding=meta["declared_encoding"])
    assert got == expected, f"{vid}: canonicalize() deviates from locked golden output"


@pytest.mark.parametrize("vid", VECTORS)
def test_vector_meta_consistency(vid: str):
    d = VECTOR_ROOT / vid
    meta = json.loads((d / "meta.json").read_text())
    assert meta["canonicalizer_version"] == CANONICALIZER_VERSION
    assert meta["applied_rules"] == list(APPLIED_RULES_V0)
    assert meta["input_bytes"] == (d / "input.bin").stat().st_size
    assert meta["expected_output_bytes"] == (d / "expected_output.bin").stat().st_size


def test_script_safety_vectors_cover_req_can_005():
    """REQ-CAN-005 spot-check independent of file contents: combining marks,
    ZWJ and ZWNJ survive canonicalization byte-exactly."""
    s = "प्रय\u00adत्न‌ज्ञ‍".encode("utf-8")
    out = canonicalize(s).decode("utf-8")
    assert "\u00ad" not in out
    for cp in ("\u094d", "\u0901", "\u200c", "\u200d"):
        assert cp in out
